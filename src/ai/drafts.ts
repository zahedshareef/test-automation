import fs from 'node:fs';
import path from 'node:path';
import { loadConfig } from '../core/config.ts';
import { JiraClient } from '../integrations/jira.ts';
import { TESTS_DIR } from '../runner/playwright.ts';
import { CopilotAI } from './copilot.ts';

const DRAFTS = path.join(TESTS_DIR, 'drafts');
const HELPERS = `- fixture "app": app.goto(path) navigates and waits for Blazor to be ready; app.waitForReady() waits after client-side navigation; app.page is the Playwright page
- fixture "page": the standard Playwright page, already signed in as the test user through Duende IdentityServer
- every test automatically fails if the Blazor error banner (#blazor-error-ui) is visible at the end`;

/** Uses Copilot to draft Playwright tests for Jira issues into tests/drafts/ for review. */
export async function draftTests(keys: string[], pageNotes?: string): Promise<{ key: string; file: string }[]> {
  const cfg = loadConfig();
  const ai = new CopilotAI(cfg);
  if (!ai.enabled) throw new Error('Copilot is not configured: set the GitHub token and AI endpoint in Settings.');
  const issues = await new JiraClient(cfg).getIssues(keys);
  if (!issues.length) throw new Error('No matching Jira issues found.');
  const exampleTest = fs.readFileSync(path.join(TESTS_DIR, 'regression', '_template.spec.ts'), 'utf8');
  fs.mkdirSync(DRAFTS, { recursive: true });
  const out: { key: string; file: string }[] = [];
  for (const issue of issues) {
    const code = await ai.draftTest(issue, { exampleTest, helpers: HELPERS, pageNotes });
    const file = path.join(DRAFTS, `${issue.key}.spec.ts`);
    const header = `// DRAFT generated by GitHub Copilot from ${issue.key} on ${new Date().toISOString().slice(0, 10)}.\n// Review it, fix every TODO(review), then promote it to a suite folder. Drafts are never run.\n`;
    fs.writeFileSync(file, header + code.replace(/from ['"]\.\.\/support\/fixtures['"]/g, "from '../support/fixtures'"));
    out.push({ key: issue.key, file: path.relative(TESTS_DIR, file) });
  }
  return out;
}

export function listDrafts(): { name: string; content: string; modified: string }[] {
  if (!fs.existsSync(DRAFTS)) return [];
  return fs
    .readdirSync(DRAFTS)
    .filter((f) => f.endsWith('.spec.ts'))
    .map((f) => ({ name: f, content: fs.readFileSync(path.join(DRAFTS, f), 'utf8'), modified: fs.statSync(path.join(DRAFTS, f)).mtime.toISOString() }));
}

const safeName = (n: string) => {
  if (!/^[\w.-]+\.spec\.ts$/.test(n)) throw new Error('Invalid draft name');
  return n;
};

export function saveDraft(name: string, content: string): void {
  fs.writeFileSync(path.join(DRAFTS, safeName(name)), content);
}

/** Moves a reviewed draft into tests/regression so it becomes part of the suite. */
export function promoteDraft(name: string): string {
  const src = path.join(DRAFTS, safeName(name));
  const content = fs.readFileSync(src, 'utf8').replace(/^\/\/ DRAFT generated[^\n]*\n\/\/ Review it[^\n]*\n/, '');
  if (/TODO\(review\)/.test(content)) throw new Error('Resolve every TODO(review) comment before promoting this draft.');
  const dest = path.join(TESTS_DIR, 'regression', name);
  if (fs.existsSync(dest)) throw new Error(`tests/regression/${name} already exists.`);
  fs.writeFileSync(dest, content);
  fs.unlinkSync(src);
  return path.relative(TESTS_DIR, dest);
}

export function deleteDraft(name: string): void {
  fs.unlinkSync(path.join(DRAFTS, safeName(name)));
}
